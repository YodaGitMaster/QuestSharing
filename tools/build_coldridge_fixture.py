"""Build tests/data/coldridge_valley.lua: the real Classic QuestieDB rows for a level-1 gnome mage in Coldridge Valley.

Source: a local QuestieDB checkout (default /tmp/qdbrepo/QuestieDB-master). Output uses named keys
(QUESTIE_QUESTS / QUESTIE_NPCS / QUESTIE_OBJECTS / QUESTIE_ITEMS) like the test harness tables.
  /tmp/qs-test-env/bin/python tools/build_coldridge_fixture.py [QUESTIEDB_DIR]
"""
import pathlib
import sys

import lupa.lua51 as lupa

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/qdbrepo/QuestieDB-master") / "data" / "Classic"
OUT = ROOT / "tests" / "data" / "coldridge_valley.lua"
# Every quest a gnome mage can start in Coldridge Valley (Anvilmar area, Dun Morogh zone 1, x 15-38, y 60-84).
QUESTS = [179, 170, 182, 183, 218, 233, 234, 282, 420, 2160, 3114, 3361, 3364, 3365]

L = lupa.LuaRuntime()
L.execute('QuestieDB={}; QuestieLoader={ImportModule=function() return QuestieDB end, CreateModule=function() return QuestieDB end}')
for name in ("classicQuestDB.lua", "classicNpcDB.lua", "classicObjectDB.lua", "classicItemDB.lua"):
    L.execute((SRC / name).read_text(encoding="utf-8", errors="replace"))
L.execute('''
for _, k in ipairs({"questData", "npcData", "objectData", "itemData"}) do
  if type(QuestieDB[k]) == "string" then QuestieDB[k] = loadstring(QuestieDB[k])() end
end
local function named(row, keys)
  local t = {}
  for k, i in pairs(keys) do if row[i] ~= nil then t[k] = row[i] end end
  return t
end
function build(ids)
  local D = QuestieDB
  local out = { quests = {}, npcs = {}, objects = {}, items = {} }
  local function npc(id) if id and D.npcData[id] and not out.npcs[id] then
    local n = named(D.npcData[id], D.npcKeys); n.waypoints = nil; n.questStarts = nil; n.questEnds = nil; out.npcs[id] = n end end
  local function obj(id) if id and D.objectData[id] and not out.objects[id] then
    local o = named(D.objectData[id], D.objectKeys); o.questStarts = nil; o.questEnds = nil; out.objects[id] = o end end
  local function item(id) if id and D.itemData[id] and not out.items[id] then
    local it = named(D.itemData[id], D.itemKeys); out.items[id] = it
    for _, n in ipairs(it.npcDrops or {}) do npc(n) end
    for _, o in ipairs(it.objectDrops or {}) do obj(o) end end end
  for _, id in ipairs(ids) do
    local q = named(D.questData[id], D.questKeys); out.quests[id] = q
    for _, part in ipairs({ q.startedBy or {}, q.finishedBy or {} }) do
      for _, n in ipairs(part[1] or {}) do npc(n) end
      for _, o in ipairs(part[2] or {}) do obj(o) end
      for _, i in ipairs(part[3] or {}) do item(i) end
    end
    local ob = q.objectives or {}
    for _, e in ipairs(ob[1] or {}) do npc(e[1]) end
    for _, e in ipairs(ob[2] or {}) do obj(e[1]) end
    for _, e in ipairs(ob[3] or {}) do item(e[1]) end
    for _, e in ipairs(ob[5] or {}) do for _, n in ipairs(e[1] or {}) do npc(n) end; npc(e[2]) end
    item(q.sourceItemId)
  end
  return out
end
local function ser(v)
  local t = type(v)
  if t == "string" then return string.format("%q", v) end
  if t ~= "table" then return tostring(v) end
  local maxi, names = 0, {}
  for k in pairs(v) do
    if type(k) == "number" and k >= 1 and k == math.floor(k) then if k > maxi then maxi = k end
    else names[#names + 1] = k end
  end
  local parts = {}
  -- positional, nil holes kept explicit (objectives = {nil, nil, {...}})
  for i = 1, maxi do parts[i] = v[i] == nil and "nil" or ser(v[i]) end
  table.sort(names, function(a, b) return tostring(a) < tostring(b) end)
  for _, k in ipairs(names) do
    parts[#parts + 1] = (type(k) == "string" and k:match("^[%a_][%w_]*$") and k or "[" .. ser(k) .. "]") .. "=" .. ser(v[k])
  end
  return "{" .. table.concat(parts, ",") .. "}"
end
function dump(out)
  local lines = { "-- AUTO GENERATED by tools/build_coldridge_fixture.py from Classic QuestieDB. Do not edit by hand." }
  for _, part in ipairs({ { "QUESTIE_QUESTS", out.quests }, { "QUESTIE_NPCS", out.npcs }, { "QUESTIE_OBJECTS", out.objects }, { "QUESTIE_ITEMS", out.items } }) do
    lines[#lines + 1] = part[1] .. "={"
    local ids = {}
    for id in pairs(part[2]) do ids[#ids + 1] = id end
    table.sort(ids)
    for _, id in ipairs(ids) do lines[#lines + 1] = " [" .. id .. "]=" .. ser(part[2][id]) .. "," end
    lines[#lines + 1] = "}"
  end
  return table.concat(lines, "\\n") .. "\\n"
end
''')
ids = L.table(*QUESTS)
OUT.parent.mkdir(exist_ok=True)
text = L.eval("dump")(L.eval("build")(ids))
# Quest XP from QuestieDB's support/QuestXP/xpDB-classic.lua ({level, xp} per quest).
L.execute('QuestXP = {}; QuestieLoader = {ImportModule = function() return QuestXP end}')
L.execute((SRC.parent.parent / "support" / "QuestXP" / "xpDB-classic.lua").read_text(encoding="utf-8", errors="replace"))
rows = ",".join("[%d]={%s,%s}" % (q, L.eval("QuestXP.db[%d][1]" % q), L.eval("QuestXP.db[%d][2]" % q)) for q in QUESTS)
text += "QUESTIE_XP={" + rows + "}\n"
OUT.write_text(text)
print("wrote", OUT, OUT.stat().st_size, "bytes")
