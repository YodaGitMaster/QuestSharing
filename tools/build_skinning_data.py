"""Regenerate QuestSharing/SkinningData.lua: which creatures can be skinned for which item, and the chance.

QuestieDB has no skinning loot (Light Hide / Light Leather have no creature drops there), so this small table is bundled.
Source: CMaNGOS classic-db (creature_template.SkinningLootId -> skinning_loot_template), factual game data only.

Usage: python3 tools/build_skinning_data.py path/to/ClassicDB_1_12_1.sql   (gunzip it first)
Runtime never downloads anything. Creature positions and levels still come from the installed QuestieDB.
"""
import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = "https://github.com/cmangos/classic-db (Full_DB/ClassicDB_1_12_1_z2815.sql.gz)"
MIN_CHANCE = 1.0  # percent; rarer skins are noise for "where do I farm this"


def tuples(line):
    s, i, out = line, line.index("VALUES") + 6, []
    n = len(s)
    while i < n:
        while i < n and s[i] in " ,":
            i += 1
        if i >= n or s[i] == ";":
            break
        i += 1
        row = []
        while True:
            if s[i] == "'":
                j, buf = i + 1, []
                while True:
                    if s[j] == "\\":
                        buf.append(s[j + 1]); j += 2; continue
                    if s[j] == "'":
                        if s[j + 1] == "'":
                            buf.append("'"); j += 2; continue
                        break
                    buf.append(s[j]); j += 1
                row.append("".join(buf)); i = j + 1
            else:
                j = i
                while s[j] not in ",)":
                    j += 1
                tok = s[i:j]; i = j
                row.append(None if tok == "NULL" else float(tok) if ("." in tok or "e" in tok.lower()) else int(tok))
            if s[i] == ",":
                i += 1
                continue
            i += 1
            break
        out.append(row)
    return out


def read(path, table):
    rows, columns, grab = [], [], False
    with open(path, encoding="utf8", errors="replace") as f:
        for line in f:
            if line.startswith(f"CREATE TABLE `{table}`"):
                grab = True
            elif grab and line.startswith(")"):
                grab = False
            elif grab:
                m = re.match(r"\s+`(\w+)`", line)
                if m:
                    columns.append(m.group(1))
            elif line.startswith(f"INSERT INTO `{table}` VALUES"):
                rows += tuples(line.rstrip("\n"))
    return columns, rows


def main(path):
    _, skin = read(path, "skinning_loot_template")
    cols, creatures = read(path, "creature_template")
    entry, loot = cols.index("Entry"), cols.index("SkinningLootId")
    template = collections.defaultdict(list)
    for entry_id, item, chance, *_ in skin:
        if chance >= MIN_CHANCE:
            template[entry_id].append((item, chance))
    items = collections.defaultdict(list)
    for row in creatures:
        for item, chance in template.get(row[loot], []) if row[loot] else []:
            items[item].append((row[entry], round(chance * 10)))
    out = ["-- AUTO GENERATED by tools/build_skinning_data.py - do not edit.",
           f"-- Source: {SOURCE}; CMaNGOS data, factual drop table only.",
           "-- [item id] = { creature id, chance in tenths of a percent, ... }",
           "local ADDON, ns = ...", "ns.skinningData = {"]
    for item in sorted(items):
        flat = ",".join(f"{npc},{chance}" for npc, chance in sorted(items[item]))
        out.append(f"[{item}]={{{flat}}},")
    out.append("}")
    target = ROOT / "QuestSharing" / "SkinningData.lua"
    target.write_text("\n".join(out) + "\n", encoding="utf8")
    print(f"{target}: {len(items)} items, {sum(len(v) for v in items.values())} creature links")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
